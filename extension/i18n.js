let tiLang = (() => {
  const ui = String(chrome.i18n?.getUILanguage?.() || 'en').toLowerCase().split(/[-_]/)[0];
  return TI_MSGS[ui] ? ui : 'en';
})();

/** Uygulamanın dilini (varsa) yükler; değişince haber verir. */
function tiLoadLang(onChange) {
  chrome.storage.local.get({ appLang: '' }, (s) => {
    if (s.appLang && TI_MSGS[s.appLang] && s.appLang !== tiLang) {
      tiLang = s.appLang;
      onChange?.();
    }
  });
  chrome.storage.onChanged.addListener((c) => {
    const v = c.appLang?.newValue;
    if (v && TI_MSGS[v] && v !== tiLang) {
      tiLang = v;
      onChange?.();
    }
  });
}

function tiT(key, params) {
  const v = (TI_MSGS[tiLang] && TI_MSGS[tiLang][key]) ?? TI_MSGS.en[key] ?? key;
  return params ? v.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m)) : v;
}
